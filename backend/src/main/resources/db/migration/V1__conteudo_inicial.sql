-- Conteudo dinamico do site: participantes, parceiros e numeros de impacto.
-- A coluna "ordem" define a ordem de exibicao no site (menor primeiro).

CREATE TABLE participante (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome    VARCHAR(120) NOT NULL,
    curso   VARCHAR(120) NOT NULL,
    periodo VARCHAR(40)  NOT NULL,
    ordem   INTEGER      NOT NULL DEFAULT 0
);

CREATE TABLE parceiro (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(160) NOT NULL,
    categoria VARCHAR(20)  NOT NULL CHECK (categoria IN ('TRIAGEM', 'BENEFICIADA', 'PALESTRA')),
    descricao VARCHAR(300) NOT NULL,
    ordem     INTEGER      NOT NULL DEFAULT 0
);

CREATE TABLE metrica_impacto (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    valor     VARCHAR(20)  NOT NULL,
    descricao VARCHAR(300) NOT NULL,
    ordem     INTEGER      NOT NULL DEFAULT 0
);

